    /* ═══════════════════════════════════════════════════════════════
       SSR WAVE PATH (PHP sine, JS replaces on load)
    ═══════════════════════════════════════════════════════════════ */
    private function generate_ssr_path( $width, $height, $granularity, $seed, $intensity ) {
        $seg_w  = $width / $granularity;
        $base_y = $height;
        $points = [ [ 0, $base_y ] ];
        for ( $i = 0; $i <= $granularity; $i++ ) {
            $x    = $i * $seg_w;
            $wave = sin( ( $i / $granularity ) * M_PI * 2 ) * $height * $intensity * 0.5;
            $y    = max( 0, min( $base_y, $base_y - $height * $intensity * 0.5 + $wave ) );
            $points[] = [ $x, $y ];
        }
        $points[] = [ $width, $base_y ];
        $points[] = [ 0, $base_y ];
        $d = 'M 0,' . $base_y;
        for ( $j = 1; $j < count( $points ) - 2; $j++ ) {
            $p0 = $points[$j - 1]; $p1 = $points[$j]; $p2 = $points[$j + 1];
            $cx1 = ( $p0[0] + $p1[0] ) / 2; $cx2 = ( $p1[0] + $p2[0] ) / 2;
            $d .= ' C ' . round($cx1,2) . ',' . round($p0[1],2) . ' ' . round($cx2,2) . ',' . round($p1[1],2) . ' ' . round($p2[0],2) . ',' . round($p2[1],2);
        }
        $d .= ' L ' . $width . ',' . $base_y . ' L 0,' . $base_y . ' Z';
        return $d;
    }

