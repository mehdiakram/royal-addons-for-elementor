    /* ═══════════════════════════════════════════════════════════════
       PRESET MERGE
    ═══════════════════════════════════════════════════════════════ */
    private function merge_preset( $settings ) {
        $key = $settings['preset'] ?? 'none';
        if ( $key === 'none' ) return $settings;
        $p = self::get_preset_config( $key );
        if ( ! $p ) return $settings;

        $map = [
            'granularity' => [ 'size' => $p['granularity'] ?? null ],
            'intensity'   => [ 'size' => $p['intensity']   ?? null ],
            'seed'        => $p['seed']        ?? null,
            'randomness'  => $p['randomness']  ?? null,
            'height_desktop' => [ 'size' => $p['height'] ?? null ],
            'anim_speed'  => [ 'size' => $p['anim_speed'] ?? null ],
            'hover_morph' => $p['hover_morph'] ?? null,
            'blur_enabled'=> $p['blur']        ?? null,
            'glow_enabled'=> $p['glow']        ?? null,
            'glow_color'  => $p['glow_color']  ?? null,
            'glow_blur'   => [ 'size' => $p['glow_blur'] ?? null ],
        ];
        foreach ( $map as $field => $val ) {
            if ( $val !== null && ! ( is_array( $val ) && ( $val['size'] ?? null ) === null ) ) {
                $settings[$field] = $val;
            }
        }
        if ( isset( $p['anim_type'] ) && ( $settings['anim_type'] ?? 'float' ) !== 'none' ) {
            $settings['anim_type'] = $p['anim_type'];
        }
        return $settings;
    }

    /* ═══════════════════════════════════════════════════════════════
       BUILD LAYERS DATA (for JS data attribute)
    ═══════════════════════════════════════════════════════════════ */
    private function build_layers_data( $settings ) {
        $preset_key = $settings['preset'] ?? 'none';
        $preset     = ( $preset_key !== 'none' ) ? self::get_preset_config( $preset_key ) : null;

        if ( $preset && ! empty( $preset['layers'] ) && empty( $settings['layers'] ) ) {
            $raw = $preset['layers'];
        } else {
            $raw = ! empty( $settings['layers'] ) ? $settings['layers'] : [];
        }

        $out = [];
        foreach ( $raw as $layer ) {
            $fill_type   = $layer['fill_type']  ?? 'solid';
            $opacity     = isset( $layer['opacity'] ) ? floatval( $layer['opacity'] ) : ( isset( $layer['layer_opacity']['size'] ) ? floatval( $layer['layer_opacity']['size'] ) : 1.0 );
            $seed_offset = isset( $layer['seed_offset'] ) ? intval( $layer['seed_offset'] ) : 0;
            $entry = [ 'fillType' => $fill_type, 'opacity' => $opacity, 'seedOffset' => $seed_offset ];

            if ( $fill_type === 'solid' ) {
                $entry['color'] = $layer['color'] ?? ( $layer['layer_color'] ?? '#4f46e5' );
            } elseif ( $fill_type === 'gradient' || $fill_type === 'radial' ) {
                $entry['gradientStart'] = $layer['gradient_start'] ?? '#4f46e5';
                $entry['gradientEnd']   = $layer['gradient_end']   ?? '#818cf8';
                if ( $fill_type === 'gradient' ) {
                    $entry['gradientAngle'] = isset( $layer['gradient_angle']['size'] ) ? intval( $layer['gradient_angle']['size'] ) : ( isset( $layer['gradient_angle'] ) ? intval( $layer['gradient_angle'] ) : 180 );
                }
            }
            $out[] = $entry;
        }
        return $out;
    }

